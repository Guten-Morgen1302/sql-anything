import fs from 'node:fs';
import path from 'node:path';
import type { FixRecord } from '../fix/types.js';
import { fmtMs, fmtX, renderCard, type CardData } from './card.js';

export function loadFixes(runDir: string): FixRecord[] {
  const root = path.join(runDir, 'fixes');
  if (!fs.existsSync(root)) return [];
  return fs
    .readdirSync(root)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .flatMap((d) => {
      const f = path.join(root, d, 'patch.json');
      return fs.existsSync(f) ? [JSON.parse(fs.readFileSync(f, 'utf8')) as FixRecord] : [];
    });
}

/** Headline = the end-to-end number when there is one, else the query-level number. */
export function cardFor(r: FixRecord, projectRoot: string, label?: string): CardData | null {
  const callsite = r.callsite ? relPath(r.callsite, projectRoot) : null;
  if (r.check && Number.isFinite(r.check.wall.speedup.point)) {
    const w = r.check.wall;
    const runs = r.check.gates.find((g) => g.name === 'parity')?.measured.match(/^(\d+)\/(\d+)/);
    return {
      findingId: r.findingId,
      kind: r.kind,
      callsite,
      sql: r.sql,
      speedup: w.speedup.point,
      speedupLo: w.speedup.lo,
      samples: w.speedup.n,
      before: { p50: w.baselineP50Ms, p95: w.baselineP95Ms },
      after: { p50: w.patchedP50Ms, p95: w.patchedP95Ms },
      planBefore: r.verify?.plans?.before,
      planAfter: r.verify?.plans?.after,
      queries: Number.isFinite(r.check.queriesPerRun.baseline) ? { before: r.check.queriesPerRun.baseline, after: r.check.queriesPerRun.patched } : undefined,
      parity: { ok: runs ? Number(runs[1]) : w.speedup.n, total: runs ? Number(runs[2]) : w.speedup.n, what: 'runs' },
      level: 'endpoint',
      label,
    };
  }
  const v = r.verify;
  if (!v?.speed) return null;
  return {
    findingId: r.findingId,
    kind: r.kind,
    callsite,
    sql: r.sql,
    speedup: v.speed.speedup.point,
    speedupLo: v.speed.speedup.lo,
    samples: v.speed.speedup.n,
    before: { p50: v.speed.baseP50Ms, p95: v.speed.baseP95Ms },
    after: { p50: v.speed.patchedP50Ms, p95: v.speed.patchedP95Ms },
    planBefore: v.plans?.before,
    planAfter: v.plans?.after,
    parity: { ok: v.verified, total: v.replayed, what: 'replayed' },
    level: 'query',
    label,
  };
}

function relPath(p: string, root: string): string {
  const m = /^(.*):(\d+):(\d+)$/.exec(p);
  if (!m) return p;
  const f = path.isAbsolute(m[1]) ? path.relative(root, m[1]) : m[1];
  return `${f.split(path.sep).join('/')}:${m[2]}`;
}

export function markdownFor(r: FixRecord, c: CardData, svgName: string): string {
  const change = r.migrationSql ? `\`\`\`sql\n${r.migrationSql}\n\`\`\`` : r.rewrites ? `SQL rewrite for \`${Object.keys(r.rewrites).join(', ')}\`` : `Code change in ${(r.changedFiles ?? []).map((f) => `\`${f}\``).join(', ')}`;
  const rollback = r.downSql ? `Roll back: \`${r.downSql.trim()}\`` : r.patchFile ? `Apply: \`git apply ${r.patchFile}\` · Roll back: \`git apply -R ${r.patchFile}\`` : 'Nothing to roll back: no source change.';
  return `### ${r.findingId} · ${r.kind}: ${fmtX(c.speedup)} faster

![benchmark](${svgName})

| | before | after |
|---|---:|---:|
| p50 | ${fmtMs(c.before.p50)} | ${fmtMs(c.after.p50)} |
| p95 | ${fmtMs(c.before.p95)} | ${fmtMs(c.after.p95)} |
${c.queries ? `| queries per run | ${c.queries.before} | ${c.queries.after} |\n` : ''}${c.planBefore && c.planAfter ? `| plan | \`${c.planBefore.slice(0, 90)}\` | \`${c.planAfter.slice(0, 90)}\` |\n` : ''}
**Change**

${change}

${c.callsite ? `Issued from \`${c.callsite}\`. ` : ''}${rollback}

**Verification**: ${c.parity.ok}/${c.parity.total} ${c.parity.what} ${c.level === 'endpoint' ? 'with identical canonical output' : 'row-for-row identical'}; speedup ${fmtX(c.speedup)} (95% CI lower bound ${fmtX(c.speedupLo)}, n=${c.samples}), randomized interleaved A/B on identical database clones${r.verify ? `, write and regression guards passed` : ''}.

<sub>${c.label ? `${c.label}. ` : ''}Replay-verified on captured inputs against one data snapshot: evidence, not proof. Production data, statistics and plans can differ. Timings include the capture hook's overhead (about 3 µs per query). Attempts needed: ${r.attempts}. Generated by sql-anything.</sub>
`;
}

export interface ReportOptions {
  runDir: string;
  ids?: string[];
  outDir?: string;
  label?: string;
  projectRoot?: string;
}

export interface ReportOutcome {
  files: string[];
  markdown: string;
  cards: { id: string; file: string }[];
}

export function writeReport(o: ReportOptions): ReportOutcome {
  const out = path.resolve(o.outDir ?? path.join(o.runDir, 'report'));
  fs.mkdirSync(out, { recursive: true });
  const fixes = loadFixes(o.runDir).filter((f) => !o.ids?.length || o.ids.includes(f.findingId));
  const files: string[] = [];
  const cards: ReportOutcome['cards'] = [];
  const parts: string[] = [];
  for (const r of fixes) {
    const c = cardFor(r, o.projectRoot ?? process.cwd(), o.label);
    if (!c) continue;
    const svgName = `card-${r.findingId}.svg`;
    fs.writeFileSync(path.join(out, svgName), renderCard(c));
    files.push(path.join(out, svgName));
    cards.push({ id: r.findingId, file: path.join(out, svgName) });
    parts.push(markdownFor(r, c, svgName));
  }
  const markdown = parts.length ? parts.join('\n---\n\n') : '_No verified fixes in this run._\n';
  const md = path.join(out, 'report.md');
  fs.writeFileSync(md, markdown);
  files.unshift(md);
  return { files, markdown, cards };
}
